// Copies the handful of brand paths HelloQR needs out of simple-icons (CC0) so the
// full icon set never reaches the client bundle. Run: node scripts/gen-icons.mjs
import { writeFileSync } from "node:fs";
import * as icons from "simple-icons";

const wanted = {
  x: "siX",
  github: "siGithub",
  instagram: "siInstagram",
  youtube: "siYoutube",
  threads: "siThreads",
  medium: "siMedium",
  devto: "siDevdotto",
  hashnode: "siHashnode",
  peerlist: "siPeerlist",
  leetcode: "siLeetcode",
  kaggle: "siKaggle",
  stackoverflow: "siStackoverflow",
  discord: "siDiscord",
  telegram: "siTelegram",
  whatsapp: "siWhatsapp",
  calendly: "siCalendly",
  behance: "siBehance",
  dribbble: "siDribbble",
};

const lines = Object.entries(wanted).map(([key, name]) => {
  const icon = icons[name];
  if (!icon) {
    throw new Error(`simple-icons has no ${name}`);
  }
  return `  ${key}: { hex: "#${icon.hex}", path: ${JSON.stringify(icon.path)} },`;
});

writeFileSync(
  new URL("../src/lib/brandPaths.ts", import.meta.url),
  `// Generated by scripts/gen-icons.mjs from simple-icons (CC0). Do not edit by hand.\n` +
    `export const brandPaths: Record<string, { hex: string; path: string }> = {\n${lines.join("\n")}\n};\n`,
);
console.log(`wrote ${lines.length} icons`);
